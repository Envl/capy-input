"""Validate the Apple string catalogs and generate the typed Swift accessors."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FOLDER = ROOT / "Apple/Localization"
LOCALES = {"en", "zh-Hans", "zh-Hant"}
PLACEHOLDER = re.compile(r"%(?:(\d+)\$)?(lld|@|%)")


def unique_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate key: {key}")
        result[key] = value
    return result


def signature(value):
    if "%" in PLACEHOLDER.sub("", value):
        raise ValueError(f"Invalid placeholder: {value}")
    matches = [pair for pair in PLACEHOLDER.findall(value) if pair[1] != "%"]
    indexed = sorted((int(position or index), kind) for index, (position, kind) in enumerate(matches, 1))
    if [position for position, _ in indexed] != list(range(1, len(matches) + 1)):
        raise ValueError(f"Invalid argument positions: {value}")
    return [kind for _, kind in indexed]


def catalog(path):
    content = json.loads(path.read_text(), object_pairs_hook=unique_keys)
    if content["sourceLanguage"] != "en":
        raise ValueError(f"Unexpected source language in {path}")
    entries = {}
    for key, item in content["strings"].items():
        if set(item["localizations"]) != LOCALES:
            raise ValueError(f"Missing or unexpected languages: {key}")
        values = {}
        for locale, translation in item["localizations"].items():
            unit = translation["stringUnit"]
            if unit["state"] != "translated" or not unit["value"].strip():
                raise ValueError(f"Missing translation: {locale}/{key}")
            values[locale] = unit["value"]
        if any(signature(text) != signature(values["en"]) for text in values.values()):
            raise ValueError(f"Incompatible placeholders: {key}")
        entries[key] = values
    return entries


def swift_source(entries):
    lines = [
        "// Generated by Scripts/localization.py --generate from Localizable.xcstrings.",
        "import Foundation", "", "enum L10n {",
        "    private static func text(_ key: String, _ english: String) -> String {",
        "        let bundle = InterfaceLanguage.currentBundle",
        "        return bundle.localizedString(forKey: key, value: english, table: nil)",
        "    }", "",
    ]
    for key, values in sorted(entries.items()):
        value = values["en"]
        lookup = f'text("{key}", {json.dumps(value, ensure_ascii=False)})'
        kinds = signature(value)
        if not kinds:
            lines.append(f"    static var {key}: String {{ {lookup} }}")
            continue
        names = ["page", "total"] if key == "pageOf" else ["value"]
        if len(names) != len(kinds):
            raise ValueError(f"Define argument names for {key}")
        parameters = ", ".join(f"_ {name}: {'Int' if kind == 'lld' else 'String'}" for name, kind in zip(names, kinds))
        arguments = ", ".join(f"Int64({name})" if kind == "lld" else name for name, kind in zip(names, kinds))
        lines.extend([f"    static func {key}({parameters}) -> String {{",
                      f"        String(format: {lookup}, locale: InterfaceLanguage.currentLocale, {arguments})", "    }"])
    return "\n".join(lines + ["}", ""])


def check_sinks():
    sinks = re.compile(r'\b(?:Text|Label|Button|Toggle|Picker|Section|DisclosureGroup|LabeledContent|TextField|SecureField|ContentUnavailableView|AppError|navigationTitle|accessibilityLabel|accessibilityHint|setTitle)\(\s*"([^"]+)"|\b(?:accessibilityLabel|accessibilityHint)\s*=\s*"([^"]+)"')
    for source in (ROOT / "Apple").rglob("*.swift"):
        for number, line in enumerate(source.read_text().splitlines(), 1):
            if line.lstrip().startswith("//"):
                continue
            if re.search(r'\b(?:NSLocalizedString|String\(localized:|localizedString\(forKey:)', line) and source != FOLDER / "L10n.swift":
                raise ValueError(f"{source.name}:{number}: use a typed localization")
            for match in sinks.finditer(line):
                raise ValueError(f"{source.name}:{number}: localize {match.group()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", action="store_true")
    parser.add_argument("--catalog-only", action="store_true", help="Check the declared Xcode build inputs")
    args = parser.parse_args()
    entries = catalog(FOLDER / "Localizable.xcstrings")
    generated = FOLDER / "L10n.swift"
    expected = swift_source(entries)
    if args.generate:
        generated.write_text(expected)
    elif generated.read_text() != expected:
        raise ValueError("Run python3 Scripts/localization.py --generate")
    if not args.catalog_only:
        check_sinks()
    print(f"Validated {len(entries)} strings in {len(LOCALES)} languages")
